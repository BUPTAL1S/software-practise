package com.lab.sipim;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.greaterThanOrEqualTo;
import static org.hamcrest.Matchers.hasSize;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.lab.sipim.repo.RoomRepository;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.TestPropertySource;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest
@AutoConfigureMockMvc
@TestPropertySource(properties = "SIPIM_DB=./target/test-room.db")
class RoomApiTest {

    static {
        try {
            Files.deleteIfExists(Path.of("target/test-room.db"));
        } catch (IOException ex) {
            throw new ExceptionInInitializerError(ex);
        }
    }

    @Autowired
    private MockMvc mvc;

    @Autowired
    private RoomRepository roomRepo;

    @Autowired
    private ObjectMapper mapper;

    @Test
    void listRoomsReturnsSeededRooms() throws Exception {
        mvc.perform(get("/api/rooms"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$", hasSize(greaterThanOrEqualTo(2))))
                .andExpect(jsonPath("$[?(@.sip_uri == 'room-101')]").exists())
                .andExpect(jsonPath("$[?(@.sip_uri == 'room-102')]").exists());
    }

    @Test
    void createRoomWithAutoGeneratedSipUri() throws Exception {
        Map<String, Object> req = Map.of(
                "name", "新研讨室A",
                "max_members", 8
        );

        mvc.perform(post("/api/rooms")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(mapper.writeValueAsString(req)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.id").isNumber())
                .andExpect(jsonPath("$.name").value("新研讨室A"))
                .andExpect(jsonPath("$.sip_uri").isNotEmpty())
                .andExpect(jsonPath("$.max_members").value(8))
                .andExpect(jsonPath("$.member_count").value(0));
    }

    @Test
    void createRoomWithCustomSipUriAndQueryByIdAndUri() throws Exception {
        Map<String, Object> req = Map.of(
                "name", "总监研讨间",
                "sip_uri", "room-999",
                "max_members", 8
        );

        mvc.perform(post("/api/rooms")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(mapper.writeValueAsString(req)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.sip_uri").value("room-999"))
                .andExpect(jsonPath("$.max_members").value(8));

        // Query by SIP URI
        mvc.perform(get("/api/rooms/room-999"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("总监研讨间"));

        // Duplicate custom SIP URI should fail with 409
        mvc.perform(post("/api/rooms")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(mapper.writeValueAsString(req)))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.error").value("room sip_uri already exists"));
    }

    @Test
    void createRoomWithInvalidSipUriOrMaxMembersReturns400() throws Exception {
        // Invalid SIP URI not starting with room-
        Map<String, Object> badUri = Map.of(
                "name", "非法房间",
                "sip_uri", "hello",
                "max_members", 8
        );
        mvc.perform(post("/api/rooms")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(mapper.writeValueAsString(badUri)))
                .andExpect(status().isBadRequest());

        // Invalid max_members not equal to 8
        Map<String, Object> badMax = Map.of(
                "name", "非法人数",
                "max_members", 3
        );
        mvc.perform(post("/api/rooms")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(mapper.writeValueAsString(badMax)))
                .andExpect(status().isBadRequest());
    }

    @Test
    void getNonExistentRoomReturns404() throws Exception {
        mvc.perform(get("/api/rooms/room-unknown-none"))
                .andExpect(status().isNotFound());
    }
}
